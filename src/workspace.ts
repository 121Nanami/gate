import { LINKS } from "./links";

type Zone = "hot" | "warm" | "cold";
type FileRow = { id: string; path: string; zone: Zone };
type State = {
  intent: string;
  failure: string;
  files: FileRow[];
  checks: Record<string, boolean>;
  worksheet: Record<string, string>;
};

const STORAGE_KEY = "shipgate.gate.v1";

const CHECKS = [
  { id: "intent", label: "Intent sentence written (user-visible outcome)" },
  { id: "failure", label: "Failure mode named in one sentence" },
  { id: "tests_happy", label: "Happy-path test asserts the outcome" },
  { id: "tests_fail", label: "Failure-path test for the top risk" },
  { id: "kill", label: "Feature flag / trivial revert exists" },
  { id: "owner", label: "Named human owns pages for 24h" },
  { id: "hot_review", label: "Every Hot file reviewed line-by-line" },
];

const WORKSHEET = [
  { id: "problem", label: "What problem does this solve?" },
  { id: "riskiest", label: "Riskiest file / line?" },
  { id: "default", label: "What if the AI invented a wrong default?" },
  { id: "notice", label: "How would a user notice failure in <5 min?" },
  { id: "revert", label: "How do we revert in <5 min?" },
];

function uid() {
  return Math.random().toString(36).slice(2, 9);
}

function load(): State {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) return JSON.parse(raw) as State;
  } catch {
    /* ignore */
  }
  return {
    intent: "",
    failure: "",
    files: [
      { id: uid(), path: "src/auth/session.ts", zone: "hot" },
      { id: uid(), path: "src/ui/Banner.tsx", zone: "cold" },
    ],
    checks: Object.fromEntries(CHECKS.map((c) => [c.id, false])),
    worksheet: Object.fromEntries(WORKSHEET.map((w) => [w.id, ""])),
  };
}

let state = load();

function save() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function escapeAttr(s: string) {
  return s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
}

function score() {
  const blocked: string[] = [];
  if (!state.intent.trim()) blocked.push("Missing intent");
  if (!state.failure.trim()) blocked.push("Missing failure mode");
  const hot = state.files.filter((f) => f.zone === "hot" && f.path.trim());
  if (hot.length && !state.checks.hot_review) blocked.push("Hot files unread");
  if (hot.length && !state.checks.tests_fail) blocked.push("Hot change needs failure test");
  for (const id of ["intent", "failure", "tests_happy", "kill", "owner"]) {
    if (!state.checks[id]) {
      blocked.push(`Unchecked: ${CHECKS.find((c) => c.id === id)?.label}`);
    }
  }
  const checkScore = CHECKS.filter((c) => state.checks[c.id]).length / CHECKS.length;
  const sheetScore =
    WORKSHEET.filter((w) => state.worksheet[w.id].trim()).length / WORKSHEET.length;
  const fileScore = state.files.some((f) => f.path.trim()) ? 1 : 0;
  const pct = Math.round((checkScore * 0.55 + sheetScore * 0.3 + fileScore * 0.15) * 100);
  return { pct, blocked: [...new Set(blocked)], ready: blocked.length === 0 && pct >= 85 };
}

function exportMd(): string {
  const files = state.files
    .filter((f) => f.path.trim())
    .map((f) => `- **${f.zone.toUpperCase()}** \`${f.path}\``)
    .join("\n");
  const ws = WORKSHEET.map((w) => `- ${w.label} ${state.worksheet[w.id] || "_TBD_"}`).join("\n");
  return `## Intent
${state.intent || "_TBD_"}

## Failure mode
${state.failure || "_TBD_"}

## Trust zones
${files || "_none_"}

## Worksheet
${ws}

## Rollback
${state.worksheet.revert || "_TBD_"}

---
Generated by Shipgate GATE.
`;
}

export function mountWorkspace(root: HTMLElement) {
  const paint = (full = true) => {
    const s = score();
    if (!full) {
      const exportEl = root.querySelector<HTMLPreElement>("#export");
      if (exportEl) exportEl.textContent = exportMd();
      const big = root.querySelector(".scorebox .big");
      if (big) big.textContent = `${s.pct}%`;
      const verdict = root.querySelector(".scorebox .verdict");
      if (verdict) {
        verdict.innerHTML = s.ready
          ? '<span class="badge ok">CLEAR TO SHIP</span>'
          : '<span class="badge block">BLOCKED</span>';
      }
      return;
    }

    root.innerHTML = `
      <section class="hero">
        <div class="panel">
          <div class="kicker">Workspace</div>
          <h2>GATE — pre-merge control</h2>
          <p class="lead">Lock intent, classify trust zones, hard-check, explain-it-back, export a PR block. Runs offline in localStorage.</p>
          <div class="cta-row">
            <a class="btn secondary" href="${LINKS.pack}" target="_blank" rel="noreferrer">Operator pack $19</a>
            <a class="btn secondary" href="${LINKS.actionRepo}" target="_blank" rel="noreferrer">GitHub Action</a>
          </div>
        </div>
        <div class="panel scorebox">
          <div class="kicker">Readiness</div>
          <div class="big">${s.pct}%</div>
          <div class="verdict">${
            s.ready
              ? '<span class="badge ok">CLEAR TO SHIP</span>'
              : '<span class="badge block">BLOCKED</span>'
          }</div>
          <ul style="margin:0.75rem 0 0;padding-left:1.1rem;color:var(--muted);font-size:0.9rem">
            ${
              s.blocked.length
                ? s.blocked
                    .slice(0, 4)
                    .map((b) => `<li>${b}</li>`)
                    .join("")
                : "<li>All hard gates satisfied.</li>"
            }
          </ul>
        </div>
      </section>

      <section class="grid-2">
        <div class="panel">
          <h2>1. Lock intent</h2>
          <label>Intent</label>
          <textarea id="intent">${escapeAttr(state.intent)}</textarea>
          <label>Failure mode</label>
          <textarea id="failure">${escapeAttr(state.failure)}</textarea>
          <h2 style="margin-top:0.5rem">2. Trust zones</h2>
          <div class="files" id="files"></div>
          <div class="cta-row" style="margin-top:0.5rem">
            <button type="button" id="add-file" class="secondary">+ Add file</button>
          </div>
        </div>
        <div class="panel">
          <h2>3. Hard checks</h2>
          <ul class="check-list" id="checks"></ul>
          <h2 style="margin-top:1rem">4. Explain-it-back</h2>
          <div id="worksheet"></div>
        </div>
      </section>

      <section class="panel" style="margin-top:1rem">
        <div class="bet-top">
          <h2 style="margin:0">5. Export PR block</h2>
          <button type="button" id="copy">Copy</button>
        </div>
        <pre class="export mono" id="export"></pre>
      </section>
    `;

    const filesEl = root.querySelector("#files")!;
    filesEl.innerHTML = state.files
      .map(
        (f) => `
      <div class="file-row" data-id="${f.id}">
        <input type="text" data-k="path" value="${escapeAttr(f.path)}" placeholder="path/to/file.ts" />
        <select data-k="zone">
          <option value="hot" ${f.zone === "hot" ? "selected" : ""}>HOT</option>
          <option value="warm" ${f.zone === "warm" ? "selected" : ""}>WARM</option>
          <option value="cold" ${f.zone === "cold" ? "selected" : ""}>COLD</option>
        </select>
        <button type="button" class="secondary" data-k="rm">×</button>
      </div>`
      )
      .join("");

    root.querySelector("#checks")!.innerHTML = CHECKS.map(
      (c) => `
      <li>
        <input type="checkbox" data-check="${c.id}" ${state.checks[c.id] ? "checked" : ""} />
        <div>${c.label}</div>
      </li>`
    ).join("");

    root.querySelector("#worksheet")!.innerHTML = WORKSHEET.map(
      (w) => `
      <label>${w.label}</label>
      <input type="text" data-ws="${w.id}" value="${escapeAttr(state.worksheet[w.id])}" />`
    ).join("");

    root.querySelector<HTMLPreElement>("#export")!.textContent = exportMd();

    const persist = (rebuild = false) => {
      save();
      paint(rebuild);
    };

    root.querySelector("#intent")!.addEventListener("input", (e) => {
      state.intent = (e.target as HTMLTextAreaElement).value;
      state.checks.intent = state.intent.trim().length > 0;
      persist(false);
    });
    root.querySelector("#failure")!.addEventListener("input", (e) => {
      state.failure = (e.target as HTMLTextAreaElement).value;
      state.checks.failure = state.failure.trim().length > 0;
      persist(false);
    });
    root.querySelector("#add-file")!.addEventListener("click", () => {
      state.files.push({ id: uid(), path: "", zone: "warm" });
      persist(true);
    });
    filesEl.querySelectorAll(".file-row").forEach((row) => {
      const id = (row as HTMLElement).dataset.id!;
      const sync = () => {
        const f = state.files.find((x) => x.id === id);
        if (!f) return;
        f.path = (row as HTMLElement).querySelector<HTMLInputElement>('[data-k="path"]')?.value ?? "";
        f.zone = ((row as HTMLElement).querySelector<HTMLSelectElement>('[data-k="zone"]')?.value ??
          "warm") as Zone;
        persist(false);
      };
      row.querySelectorAll("[data-k]").forEach((el) => {
        const k = (el as HTMLElement).dataset.k;
        if (k === "rm") {
          el.addEventListener("click", () => {
            state.files = state.files.filter((f) => f.id !== id);
            persist(true);
          });
        } else {
          el.addEventListener("input", sync);
          el.addEventListener("change", sync);
        }
      });
    });
    root.querySelectorAll<HTMLInputElement>("[data-check]").forEach((el) => {
      el.addEventListener("change", () => {
        state.checks[el.dataset.check!] = el.checked;
        persist(false);
      });
    });
    root.querySelectorAll<HTMLInputElement>("[data-ws]").forEach((el) => {
      el.addEventListener("input", () => {
        state.worksheet[el.dataset.ws!] = el.value;
        persist(false);
      });
    });
    root.querySelector("#copy")!.addEventListener("click", async () => {
      await navigator.clipboard.writeText(exportMd());
      (root.querySelector("#copy") as HTMLButtonElement).textContent = "Copied";
      setTimeout(() => {
        (root.querySelector("#copy") as HTMLButtonElement).textContent = "Copy";
      }, 1200);
    });
  };

  paint(true);
}
