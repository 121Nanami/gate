function syncFile(id: string, row: HTMLElement) {
  const f = state.files.find((x) => x.id === id);
  if (!f) return;
  const path = row.querySelector<HTMLInputElement>('[data-k="path"]')?.value ?? "";
  const zone = (row.querySelector<HTMLSelectElement>('[data-k="zone"]')?.value ?? "warm") as Zone;
  f.path = path;
  f.zone = zone;
  persist();
}

function persist(full = false) {
  save();
  if (full) render();
  else {
    const s = score();
    const exportEl = document.querySelector<HTMLPreElement>("#export");
    if (exportEl) exportEl.textContent = exportMd();
    const big = document.querySelector(".scorebox .big");
    if (big) big.textContent = `${s.pct}%`;
    const verdict = document.querySelector(".scorebox .verdict");
    if (verdict) {
      verdict.innerHTML = s.ready
        ? '<span class="badge ok">CLEAR TO SHIP</span>'
        : '<span class="badge block">BLOCKED</span>';
    }
  }
}

function escapeAttr(s: string) {
  return s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
}

