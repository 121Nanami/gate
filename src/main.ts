function uid() {
  return Math.random().toString(36).slice(2, 9);
}

function load(): State {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) return JSON.parse(raw) as State;
  } catch {
    /* ignore */
  }
  return {
    intent: "",
    failure: "",
    files: [
      { id: uid(), path: "src/auth/session.ts", zone: "hot" },
      { id: uid(), path: "src/ui/Banner.tsx", zone: "cold" },
    ],
    checks: Object.fromEntries(CHECKS.map((c) => [c.id, false])),
    worksheet: Object.fromEntries(WORKSHEET.map((w) => [w.id, ""])),
  };
}

let state = load();

function save() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function score(): { pct: number; blocked: string[]; ready: boolean } {
  const blocked: string[] = [];
  if (!state.intent.trim()) blocked.push("Missing intent");
  if (!state.failure.trim()) blocked.push("Missing failure mode");
  const hot = state.files.filter((f) => f.zone === "hot" && f.path.trim());
  if (hot.length && !state.checks.hot_review) blocked.push("Hot files unread");
  if (hot.length && !state.checks.tests_fail) blocked.push("Hot change needs failure test");
  for (const c of CHECKS) {
    if (!state.checks[c.id] && ["intent", "failure", "tests_happy", "kill", "owner"].includes(c.id)) {
      if (!blocked.some((b) => b.toLowerCase().includes(c.id))) {
        /* scored below */
      }
    }
  }
  const required = ["intent", "failure", "tests_happy", "kill", "owner"];
  for (const id of required) {
    if (!state.checks[id]) blocked.push(`Unchecked: ${CHECKS.find((c) => c.id === id)?.label}`);
  }
  const checkScore = CHECKS.filter((c) => state.checks[c.id]).length / CHECKS.length;
  const sheetScore =
    WORKSHEET.filter((w) => state.worksheet[w.id].trim()).length / WORKSHEET.length;
  const fileScore = state.files.some((f) => f.path.trim()) ? 1 : 0;
  const pct = Math.round((checkScore * 0.55 + sheetScore * 0.3 + fileScore * 0.15) * 100);
  const ready = blocked.length === 0 && pct >= 85;
  return { pct, blocked: [...new Set(blocked)], ready };
}

function exportMd(): string {
  const files = state.files
    .filter((f) => f.path.trim())
    .map((f) => `- **${f.zone.toUpperCase()}** \`${f.path}\``)
    .join("\n");
  const ws = WORKSHEET.map((w) => `- ${w.label} ${state.worksheet[w.id] || "_TBD_"}`).join("\n");
  return `## Intent
${state.intent || "_TBD_"}

## Failure mode
${state.failure || "_TBD_"}

## Trust zones
${files || "_none_"}

## Worksheet
${ws}

## Rollback
${state.worksheet.revert || "_TBD_"}

---
Generated by GATE — ship AI code you can defend.
`;
}

